export const SIGNATURE_MAX = 10;

/** 取个性签名；没有就退回到第一个性格标签 */
export function signatureOf(persona) {
  if (!persona) return '';
  const s = SIGNATURES[persona.id];
  if (s) return s;
  const tag = (persona.tags || [])[0] || '';
  return tag.slice(0, SIGNATURE_MAX);
}
