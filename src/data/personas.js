/* ---------------- 性别（★ 每个 AI 都要标，也是提示词里的背景知识） ---------------- */
export const GENDER_SIGN = { m: '♂', f: '♀' };
export const GENDER_TEXT = { m: '男', f: '女' };

/** 拿性别：老数据里没这个字段时按"男"兜底 */
export function genderOf(persona) {
  return persona && persona.gender === 'f' ? 'f' : 'm';
}

/** ♂ / ♀ （好友列表、聊天标题上标的那个符号） */
export function genderSign(persona) {
  return GENDER_SIGN[genderOf(persona)];
}

/** 性别文案（♂ 男 / ♀ 女） */
export function genderLabel(persona) {
  const g = genderOf(persona);
  return `${GENDER_SIGN[g]} ${GENDER_TEXT[g]}`;
}

/**
 * 写进提示词的那一行（**背景知识，不是话题**）
 * 目的：让台词符合性别（别人叫"哥/姐"、自称、语气），但别每句都强调性别 —— 那很假。
 */
export function genderPromptLine(persona) {
  const g = genderOf(persona);
  return `你的性别：${GENDER_TEXT[g]}（${GENDER_SIGN[g]}）。这是固定设定，说话方式、自称、别人对你的称呼都要对得上；`
    + '但**别每句都提性别**，自然的时候体现一下就够了，也别拿性别开玩笑。';
}

/**
 * 是不是**傲娇**人设（用户拍板：这一类要单独判断）
 *
 * 傲娇的关键特征是"嘴硬心软"：被表白时嘴上会说"才、才不是呢""谁要跟你在一起""笨蛋"，
 * 但**心里是答应的**。所以表白审查里要给这一类开后门：回复看上去像拒绝，也判定为答应
 * （除非她明确说"我有喜欢的人了""我们不可能"这种真的拒绝）。
 *
 * 判定依据：标签里有「傲娇」/「嘴硬」（目前是 p26「才不是傲娇」），人设里写了"傲娇"也算。
 */
export function isTsundere(persona) {
  if (!persona) return false;
  const tags = persona.tags || [];
  if (tags.some((t) => String(t).includes('傲娇') || String(t).includes('嘴硬'))) return true;
  return String(persona.prompt || '').includes('傲娇');
}

/** 拿年龄：老数据里没这个字段时按 25 兜底 */
export function ageOf(persona) {
  const n = Number(persona && persona.age);
  return Number.isFinite(n) && n > 0 ? Math.round(n) : 25;
}

/**
 * 年龄也写进提示词，但**只是背景知识**：
 * 它影响用词的年代感与分寸（18 岁和 56 岁说话不一样），但**不许主动提**，别人问了才自然答一句。
 */
export function agePromptLine(persona) {
  return `你的年龄：${ageOf(persona)} 岁。这也是背景知识 —— 它影响你说话的用词和分寸，`
    + '但**绝对不要主动提年龄**（不说自己多大、不提几零后、不说"我这年纪"）；只有别人直接问起，才随口答一句。';
}

