export const SITUATION_KEYS = Object.keys(SITUATION_LINES);

export function pickSituationLine(key, style, avoid) {
  const bucket = SITUATION_LINES[key];
  if (!bucket) return null;
  const pool = bucket[style] || bucket.balanced || [];
  const fresh = pool.filter((l) => !avoid || !avoid.has(l));
  const list = fresh.length ? fresh : pool;
  if (!list.length) return null;
  return list[Math.floor(Math.random() * list.length)];
}
